import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/Julius Tusing/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
mkdirSync('tmp/screenshots', { recursive: true });
const origin = process.env.QA_ORIGIN || 'http://127.0.0.1:8080';
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
let calls = 0;
const errors = [];
try {
  await context.addInitScript(() => {
    localStorage.setItem('uhpabUser', JSON.stringify({ id: '2', name: 'QA Student', email: 'premium@uhpab.edu', role: 'premium' }));
    localStorage.setItem('gemini_api_key', 'test-key-never-sent-to-google');
  });
  // No document text or key leaves the test browser: intercept all Gemini calls.
  await context.route('https://generativelanguage.googleapis.com/**', async route => {
    calls++;
    const prompt = JSON.parse(route.request().postData()).input;
    const start = prompt.indexOf('{"criteria":');
    const end = prompt.indexOf('\nReturn ONLY JSON:', start);
    const data = JSON.parse(prompt.slice(start, end));
    const chunk = data.evidenceChunks[0];
    const criteria = data.criteria.map(criterion => ({ id: criterion.id, checks: criterion.requirements.map(requirement => ({ index: requirement.index, verdict: 'partial', chunkId: chunk.id, quote: chunk.text.slice(0, 120), reason: 'Controlled QA response: supporting study detail is incomplete for this specific requirement.', improvement: 'Controlled QA correction: add study-specific evidence addressing this requirement in full.' })) }));
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ output_text: JSON.stringify({ criteria }) }) });
  });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/document-analysis`);
  await page.getByLabel('Or paste document text').waitFor();
  const button = page.getByRole('button', { name: 'Start marking-guide check' });
  assert.equal(await button.isDisabled(), true);
  await page.getByLabel('Or paste document text').fill('CHAPTER ONE: INTRODUCTION\n1.0 Introduction\nThis study assesses factors associated with treatment completion among adult patients at Kiyumba Health Centre IV, Kampala. The chapter presents the background, problem, objectives, questions, justification and significance of the study. The proposed work will describe patient-related and health facility-related factors in this local setting.');
  await page.getByRole('combobox').last().click();
  await page.getByRole('option', { name: 'Introduction', exact: true }).click();
  assert.equal(await button.isDisabled(), true);
  await page.getByRole('checkbox').nth(1).check();
  await button.click();
  await page.getByText('Fresh marking-guide report created').waitFor({ timeout: 30000 });
  assert.ok(calls > 0);
  assert.ok(await page.getByText('Required improvement', { exact: true }).count() > 0);
  await page.screenshot({ path: 'tmp/screenshots/strict-marking-desktop.png', fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export marking report', exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs('tmp/pdfs/strict-marking-browser-download.pdf');
  assert.equal(await download.failure(), null);
  await page.getByRole('button', { name: 'Keep this document', exact: true }).click();
  await page.getByText('Kept until you delete it', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Use seven-day deletion', exact: true }).click();
  await page.getByRole('button', { name: 'Keep this document', exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'tmp/screenshots/strict-marking-mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  assert.equal(overflow, false, 'Mobile layout must not scroll horizontally');
  await page.reload();
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await page.getByText('Fresh marking-guide report created').waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete now', exact: true }).click();
  await page.getByText('No stored document checks yet', { exact: true }).waitFor();
  await page.goto(`${origin}/marking-guide`);
  await page.getByRole('tab', { name: 'Proposal', exact: true }).click();
  await page.getByText('See where the 64 practice marks come from', { exact: true }).waitFor();
  await page.screenshot({ path: 'tmp/screenshots/strict-marking-guide-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ success: true, interceptedGeminiCalls: calls, actualModelCalls: 0, checked: ['consent', 'strict marking UI', 'PDF download', 'retention toggle', 'reload/resume', 'delete', 'mobile overflow', 'proposal rubric'] }));
} finally { await context.close(); await browser.close(); }
